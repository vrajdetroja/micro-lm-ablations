"""Generate every derived config from the baseline. Edit this script, not the YAMLs it writes.

    python configs/generate.py

  configs/ablations/  the planned Tier A and Tier B variants (one change each, except where
                      a matched comparison forces a second field; the header says why)
  configs/ladder/     the width ladder for the scaling law (C1) and the cross-scale check (C2)
  configs/reserve/    further variants, designed but not run in this study

Each file's header records its parameter counts and training FLOPs.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "src"))

from microlm.model import ModelConfig, flops_per_token, param_counts  # noqa: E402
from microlm.train.config import load_yaml  # noqa: E402

BASE = load_yaml(ROOT / "baseline.yaml")
BASE_MODEL = ModelConfig.from_dict(BASE["model"])
T = BASE["train"]["seq_len"]
TPS = BASE["train"]["tokens_per_step"]
BASE_TOKENS = BASE["train"]["total_tokens"]
BASE_FLOPS = flops_per_token(BASE_MODEL, T)["total"] * BASE_TOKENS


def model_of(overrides: dict, vocab: int = 8192) -> ModelConfig:
    return ModelConfig.from_dict({**BASE["model"], **overrides, "vocab_size": vocab})


def header(name: str, model: dict, train: dict, vocab: int, why: str | None) -> str:
    cfg = model_of(model, vocab)
    pc = param_counts(cfg)
    seq = train.get("seq_len", T)
    tokens = train.get("total_tokens", BASE_TOKENS)
    flops = flops_per_token(cfg, seq)["total"] * tokens
    lines = [
        f"# {name} (generated by configs/generate.py; do not edit by hand)",
        f"# N_non_embedding {pc['non_embedding'] / 1e6:.2f}M | N_total {pc['total'] / 1e6:.2f}M | "
        f"vocab {vocab} | {tokens / 1e6:.0f}M tokens",
        f"# {flops:.3g} training FLOPs ({flops / BASE_FLOPS:.2f}x baseline)",
    ]
    if why:
        lines.append(f"# {why}")
    return "\n".join(lines) + "\n"


def write(directory: str, name: str, model: dict | None = None, train: dict | None = None,
          vocab: int = 8192, why: str | None = None) -> None:
    model, train = model or {}, train or {}
    body = {"inherit": "../baseline.yaml", "name": name}
    if why:
        body["notes"] = why
    if model:
        body["model"] = model
    if train:
        body["train"] = train
    out = ROOT / directory / f"{name}.yaml"
    out.write_text(header(name, model, train, vocab, why) + yaml.safe_dump(body, sort_keys=False))


def equal_flops_tokens(model: dict, vocab: int) -> int:
    """Training tokens that give this model the baseline's total FLOPs, in whole steps."""
    per_token = flops_per_token(model_of(model, vocab), T)["total"]
    return max(1, round(BASE_FLOPS / per_token / TPS)) * TPS


def matched_depth(vocab: int) -> int:
    """Layers that bring total params closest to the baseline's when the vocab changes."""
    target = param_counts(model_of({}))["total"]
    return min(range(1, 25), key=lambda L: abs(param_counts(model_of({"n_layer": L}, vocab))["total"] - target))


def ladder_shape(d: int, steps: int = 1620, tokens_per_param: int = 20, window_multiple: int = 8):
    """Every ladder point trains for the same number of steps; tokens/step grows with N."""
    n = param_counts(model_of({"d_model": d, "n_head": d // 64}))["non_embedding"]
    windows = max(window_multiple, round(tokens_per_param * n / steps / T / window_multiple) * window_multiple)
    micro = max(m for m in range(1, 65) if windows % m == 0)
    return {"tokens_per_step": windows * T, "total_tokens": windows * T * steps, "micro_batch_size": micro}


def main() -> None:
    for directory in ("ablations", "ladder", "reserve"):
        (ROOT / directory).mkdir(exist_ok=True)
        for f in (ROOT / directory).glob("*.yaml"):
            f.unlink()

    # -- Tier A ---------------------------------------------------------------------------
    for pos in ("sinusoidal", "rope", "alibi", "nope"):
        write("ablations", f"pos_{pos}", {"pos_type": pos})
    for ffn in ("swiglu", "geglu", "relu2"):
        write("ablations", f"ffn_{ffn}", {"ffn_type": ffn})
    write("ablations", "norm_rmsnorm", {"norm_type": "rmsnorm"})
    write("ablations", "norm_post", {"norm_position": "post"})
    # Follow-ups (amendments to 002 and 004, 2026-10-16). The first runs showed that the raw
    # sinusoid table swamps GPT-2-scale token embeddings, and that post-LN under GPT-2 init
    # collapses to the unigram solution.
    write("ablations", "pos_sinusoidal_scaled", {"pos_type": "sinusoidal", "sinusoidal_rms": 0.02},
          why="Fixed sin/cos table rescaled to RMS 0.02, the learned table's initial magnitude.")
    write("ablations", "norm_post_torchinit", {"norm_position": "post", "init_scheme": "torch"},
          why="Post-LN with PyTorch's standard TransformerEncoderLayer initialization.")
    write("ablations", "init_torch", {"init_scheme": "torch"},
          why="Pre-LN with PyTorch's standard initialization: the init control for norm_post_torchinit.")
    write("ablations", "norm_no_final", {"final_norm": False})
    write("ablations", "sched_cosine0", train={"min_lr_ratio": 0.0})
    write("ablations", "sched_linear", train={"schedule": "linear", "min_lr_ratio": 0.0})
    write("ablations", "sched_wsd", train={"schedule": "wsd", "decay_frac": 0.2, "min_lr_ratio": 0.0})
    for L, d in ((2, 640), (12, 256), (24, 192)):
        write("ablations", f"dw_L{L}_d{d}", {"n_layer": L, "d_model": d, "n_head": d // 64},
              why=f"Depth vs width at ~10.6M non-embedding params, d_head fixed at 64 (aspect d/L = {d // L}).")

    # -- Tier B ---------------------------------------------------------------------------
    for v in (2048, 4096, 16384):
        L = matched_depth(v)
        model = {"n_layer": L}
        train = {"data_dir": f"data/fineweb_edu/bpe_{v}", "total_tokens": equal_flops_tokens(model, v)}
        write("ablations", f"vocab_{v}", model, train, vocab=v,
              why=f"Vocab {v}: total params matched to the baseline by depth (L={L}); tokens set for equal "
                  "training FLOPs. Compare in BPB.")
    write("ablations", "opt_muon", train={"optimizer": "muon", "muon_lr": 0.02})
    write("ablations", "opt_lion", train={"optimizer": "lion", "lr": 4.0e-4, "weight_decay": 1.0},
          why="Lion starting point: ~10x lower LR and ~10x higher decoupled WD than AdamW (Chen et al. 2023).")

    # -- C1/C2 width ladder (d=384 is the baseline itself) ---------------------------------
    for d in (128, 192, 256, 512):
        write("ladder", f"ladder_d{d}", {"d_model": d, "n_head": d // 64}, ladder_shape(d),
              why="Width ladder at 6 layers: 1620 steps for every size, ~20 tokens per non-embedding param.")

    # -- reserve: designed, not run ---------------------------------------------------------
    write("reserve", "sched_constant", train={"schedule": "constant"})
    write("reserve", "heads_3", {"n_head": 3})
    write("reserve", "heads_12", {"n_head": 12})
    write("reserve", "gqa_kv3", {"n_kv_head": 3})
    write("reserve", "gqa_kv2", {"n_kv_head": 2})
    write("reserve", "mqa", {"n_kv_head": 1})
    write("reserve", "untied", {"tie_embeddings": False})
    write("reserve", "ffn_mult2_L9", {"ffn_mult": 2.0, "n_layer": 9},
          why="FFN 2x with depth 9: exactly the baseline's non-embedding params (8d^2 x 9 = 12d^2 x 6).")
    write("reserve", "ffn_mult8_L4", {"ffn_mult": 8.0, "n_layer": 4},
          why="FFN 8x with depth 4: +11% non-embedding params (20d^2 x 4 vs 12d^2 x 6); no exact match exists.")

    for directory in ("ablations", "ladder", "reserve"):
        files = sorted((ROOT / directory).glob("*.yaml"))
        print(f"{directory}: {len(files)} configs")


if __name__ == "__main__":
    main()
